-- Debt Paydown: tracked debts and the credits allocated to paying them down.
--
-- The fpfl schema is owned by API-JDK (Hibernate ddl-auto: update), and API-NET never runs EF
-- migrations against it, so new tables are created with this script. Hibernate's "update" mode
-- leaves tables it doesn't know about alone. Safe to run more than once.
--
--   psql "host=... dbname=FPFL-V2 user=..." -f db/001_debt_paydown.sql
--
-- Deleting a debit removes its tracked debt; deleting a credit removes its allocations.

CREATE TABLE IF NOT EXISTS fpfl.debts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       uuid          NOT NULL,
    fk_item       bigint        NOT NULL UNIQUE REFERENCES fpfl.items (id) ON DELETE CASCADE,
    balance       numeric(14,2) NOT NULL CHECK (balance >= 0),
    apr           numeric(6,3)  NOT NULL DEFAULT 0 CHECK (apr >= 0 AND apr <= 100),
    balance_date  date          NOT NULL,
    created_at    timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_debts_user_id ON fpfl.debts (user_id);

CREATE TABLE IF NOT EXISTS fpfl.debt_allocations (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_debt         bigint       NOT NULL REFERENCES fpfl.debts (id) ON DELETE CASCADE,
    fk_credit_item  bigint       NOT NULL REFERENCES fpfl.items (id) ON DELETE CASCADE,
    percent         numeric(5,2) NOT NULL CHECK (percent > 0 AND percent <= 100),
    UNIQUE (fk_debt, fk_credit_item)
);

CREATE INDEX IF NOT EXISTS ix_debt_allocations_credit ON fpfl.debt_allocations (fk_credit_item);
